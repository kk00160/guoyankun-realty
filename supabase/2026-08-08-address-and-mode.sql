-- 1) 正確地址
--
-- 匯入回來的 address 只到路或巷（例：東橋七路），沒有門牌 ——
-- 因為原始刊登本來就不會給。實際帶看時阿坤知道確切門牌，
-- 這個欄位就是讓他把知道的東西補進系統，之後導航才會帶到門口而不是巷口。
--
-- 刻意不覆寫原本的 address：那是外部來源的原始值，
-- 蓋掉之後就永遠分不出「來源給的」跟「阿坤補的」，
-- 也沒辦法在來源更新時比對出差異。
alter table public.listings
  add column if not exists exact_address text;

-- 2) 帶看紀錄的模式
--
-- pick  ：買方自己勾想看／略過（預設，適合還在篩的階段）
-- direct：已經談好要看哪幾間，直接給買方一張帶看卡，不用他再挑一次
--
-- 為什麼需要分開：已經約好的客人再看到「想看／略過」兩顆按鈕，
-- 會以為事情還沒定案，反而回頭再問一次。
alter table public.tours
  add column if not exists mode text not null default 'pick';
